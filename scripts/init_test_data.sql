-- ====================================================================
-- AnswerAgent 测试数据集
-- ====================================================================
-- 用途：为 ReAct / Reflect 测评提供可控、覆盖多场景的种子数据
-- 覆盖场景：
--   1. 多部门对比     ← 5 个部门，员工数差异化（10/8/5/4/3）
--   2. 趋势/异常分析  ← 5 天打卡，含迟到/早退/缺卡/加班记录
--   3. 跨表 JOIN      ← user × department × check_record × device
--   4. 复杂条件筛选   ← 既/又、嵌套、子查询所需差异化数据
--   5. ask_user 触发  ← 同名员工（"张伟"在两个部门都有）
--
-- 用法：
--   mysql -uroot -p<密码> <数据库名> < scripts/init_test_data.sql
-- ====================================================================

-- 注意：会先 DROP 同名表，请确认你的数据库是测试库！
SET FOREIGN_KEY_CHECKS = 0;
DROP TABLE IF EXISTS check_record;
DROP TABLE IF EXISTS device;
DROP TABLE IF EXISTS user;
DROP TABLE IF EXISTS department;
SET FOREIGN_KEY_CHECKS = 1;


-- ====================================================================
-- 表 1：department 部门信息表
-- ====================================================================
CREATE TABLE department (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    name VARCHAR(64) NOT NULL COMMENT '部门名称',
    code VARCHAR(32) COMMENT '部门编码',
    manager_id BIGINT COMMENT '部门负责人用户ID（关联 user.id）',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='部门信息表';


-- ====================================================================
-- 表 2：user 用户信息表（员工信息）
-- ====================================================================
CREATE TABLE user (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    number VARCHAR(255) COMMENT '工号',
    name VARCHAR(64) NOT NULL COMMENT '姓名',
    password VARCHAR(64) COMMENT '密码（md5加密）',
    sex TINYINT COMMENT '性别 (0=女, 1=男)',
    birth VARCHAR(64) COMMENT '出生年月',
    user_type TINYINT DEFAULT 2 COMMENT '用户类型 (0=超级管理员, 1=管理员, 2=普通用户)',
    status TINYINT DEFAULT 0 COMMENT '账号状态 (0=正常, 1=禁用, -1=删除)',
    department_id BIGINT COMMENT '部门ID（关联 department.id）',
    email VARCHAR(255) COMMENT '邮箱',
    phone VARCHAR(11) COMMENT '手机号',
    attend_type INT DEFAULT 1 COMMENT '是否考勤 (0=不参加, 1=参加)',
    info_submitted INT DEFAULT 1 COMMENT '信息是否齐全 (0=不齐全, 1=齐全)',
    image_url TEXT COMMENT '人脸图片URL',
    video_url TEXT COMMENT '视频URL',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
    update_time DATETIME DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
    information VARCHAR(255) COMMENT '是否接受邮件提醒',
    wechat_id VARCHAR(255) COMMENT '微信ID',
    auto_check_count INT DEFAULT 0 COMMENT '每周自动打卡次数',
    emergency_name VARCHAR(255) COMMENT '紧急联系人姓名',
    emergency_phone VARCHAR(11) COMMENT '紧急联系人电话'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户/员工信息表';


-- ====================================================================
-- 表 3：device 考勤设备表
-- ====================================================================
CREATE TABLE device (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    name VARCHAR(255) COMMENT '设备名称',
    model VARCHAR(255) COMMENT '品牌型号',
    ip VARCHAR(255) COMMENT '设备IP地址',
    address VARCHAR(255) COMMENT '安装位置',
    department_id BIGINT COMMENT '所属部门ID（NULL=公共设备）',
    status TINYINT DEFAULT 0 COMMENT '设备状态 (0=正常, 1=关闭)',
    code VARCHAR(255) COMMENT '设备识别码',
    type INT DEFAULT 0 COMMENT '设备类别 (0=指纹机)'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='考勤设备表';


-- ====================================================================
-- 表 4：check_record 打卡记录表
-- ====================================================================
CREATE TABLE check_record (
    id BIGINT PRIMARY KEY AUTO_INCREMENT COMMENT '主键ID',
    check_time DATETIME COMMENT '打卡具体时间',
    type TINYINT COMMENT '打卡类型 (0=进入/上班, 1=离开/下班)',
    user_id BIGINT COMMENT '用户ID（关联 user.id）',
    create_time TIMESTAMP DEFAULT CURRENT_TIMESTAMP COMMENT '记录创建时间',
    device_id BIGINT COMMENT '打卡设备ID（关联 device.id）',
    `desc` VARCHAR(255) COMMENT '备注信息',
    INDEX idx_user_time (user_id, check_time),
    INDEX idx_check_time (check_time)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='打卡记录表';


